// Generated by the Teen Patti Pro installer.
//
// Signature verification lives here so the controller stays a thin adapter and
// the rule is stated once. Two checks, both required: recompute the digest and
// compare in constant time, and reject a timestamp outside the window or a
// nonce already seen. Constant-time comparison alone is not enough -- without
// the freshness checks a captured request replays verbatim forever.
import { Injectable, UnauthorizedException } from '@nestjs/common';
import { createHmac, timingSafeEqual } from 'crypto';
import { IdempotentLedgerService } from './ledger.schema';
import { WalletCallbackDto } from './wallet.dto';
import { teenPattiConfig } from './teen-patti.config';

const TOLERANCE_MS = 5 * 60 * 1000;

@Injectable()
export class WalletCallbackService {
  private readonly seenNonces = new Map<string, number>();

  constructor(private readonly ledger: IdempotentLedgerService) {}

  verify(raw: Buffer, headers: Record<string, string | undefined>): void {
    const ts = headers['x-timestamp'] ?? '';
    const nonce = headers['x-nonce'] ?? '';
    const sig = headers['x-signature'] ?? '';
    if (!ts || !nonce || !sig) {
      throw new UnauthorizedException('missing signature headers');
    }
    const at = Number(ts);
    if (!Number.isFinite(at) || Math.abs(Date.now() - at) > TOLERANCE_MS) {
      throw new UnauthorizedException('timestamp outside the tolerance window');
    }
    const seenAt = this.seenNonces.get(nonce);
    if (seenAt !== undefined && Date.now() - seenAt <= TOLERANCE_MS) {
      throw new UnauthorizedException('nonce replay');
    }
    const expected = createHmac(
      'sha256',
      teenPattiConfig().hmacSecret,
    )
      .update(Buffer.concat([Buffer.from(ts), Buffer.from(nonce), raw]))
      .digest('hex');
    const a = Buffer.from(expected, 'utf8');
    const b = Buffer.from(sig, 'utf8');
    if (a.length !== b.length || !timingSafeEqual(a, b)) {
      throw new UnauthorizedException('bad signature');
    }
    this.seenNonces.set(nonce, Date.now());
    if (this.seenNonces.size > 10_000) {
      // Bound the replay cache; entries older than the window are useless.
      const cutoff = Date.now() - TOLERANCE_MS;
      for (const [k, v] of this.seenNonces) {
        if (v < cutoff) this.seenNonces.delete(k);
      }
    }
  }

  async handle(dto: WalletCallbackDto) {
    return this.ledger.apply(dto);
  }
}
