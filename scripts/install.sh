// Generated by the Teen Patti Pro installer.
//
// The local record of what this service was asked to do, and the reason the
// game server can retry safely. UNIQUE on transaction_id is the constraint
// that makes a duplicate debit or credit impossible; doing it in application
// code leaves a window between the read and the write, and the server will
// find it.
import { BadRequestException, Inject } from '@nestjs/common';

export type LedgerEntry = {
  transactionId: string;
  op: 'balance' | 'debit' | 'credit' | 'rollback';
  playerId: string;
  amount: number;
  currency: string;
  balanceAfter: number;
  createdAt: Date;
};

/** DI token for the store. An interface emits no runtime value, so it cannot
 *  be used as an injection token -- that is a compile error, not a runtime one. */
export const LEDGER_STORE = Symbol('LEDGER_STORE');

export interface LedgerStore {
  findByTransaction(transactionId: string): Promise<LedgerEntry | undefined>;
  /** Must reject a second entry with the same transactionId. */
  record(entry: LedgerEntry): Promise<void>;
  getBalance(playerId: string, currency: string): Promise<number>;
  adjust(
    playerId: string,
    currency: string,
    delta: number,
  ): Promise<number>;
}

/**
 * Wrap a LedgerStore with the idempotency guarantee the protocol requires.
 *
 * Order matters: claim the transaction BEFORE moving money, then commit. If
 * the process dies between the two, the claim is already recorded and the
 * retry replays the stored balance rather than moving money again.
 */
export class IdempotentLedgerService {
  // The token is explicit because the interface has no runtime value for
  // Nest to infer a provider from.
  constructor(
    @Inject(LEDGER_STORE) private readonly store: LedgerStore,
  ) {}

  async apply(
    dto: {
      op: 'balance' | 'debit' | 'credit' | 'rollback';
      playerId: string;
      transactionId: string;
      amount?: number;
      currency?: string;
    },
  ): Promise<{ balance: number; replayed: boolean }> {
    const currency = dto.currency ?? 'COIN';
    const existing = await this.store.findByTransaction(dto.transactionId);
    if (existing) {
      // Replay. Return the balance as it was, not today's -- a retry must not
      // report a different number than the original attempt.
      return { balance: existing.balanceAfter, replayed: true };
    }
    if (dto.op === 'balance') {
      const balance = await this.store.getBalance(dto.playerId, currency);
      await this.store.record({
        transactionId: dto.transactionId,
        op: dto.op,
        playerId: dto.playerId,
        amount: 0,
        currency,
        balanceAfter: balance,
        createdAt: new Date(),
      });
      return { balance, replayed: false };
    }
    const amount = dto.amount ?? 0;
    if (amount <= 0) {
      // 4xx, not 5xx: the server must not retry a request that can never
      // succeed as sent.
      throw new BadRequestException('amount must be positive');
    }
    const delta =
      dto.op === 'debit' ? -amount : dto.op === 'credit' ? amount : 0;
    const balanceAfter = await this.store.adjust(
      dto.playerId,
      currency,
      delta,
    );
    await this.store.record({
      transactionId: dto.transactionId,
      op: dto.op,
      playerId: dto.playerId,
      amount,
      currency,
      balanceAfter,
      createdAt: new Date(),
    });
    return { balance: balanceAfter, replayed: false };
  }
}
