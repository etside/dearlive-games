// Generated by the Teen Patti Pro installer.
//
// A thin adapter. The rules that matter live in WalletCallbackService and
// IdempotentLedgerService, so they are stated once rather than restated here:
//   - verify the signature on the RAW bytes, before parsing
//   - reject a stale timestamp and a replayed nonce
//   - key the ledger write on the transaction id, not on arrival
//   - answer 4xx for a request that can never succeed as sent, so the server
//     stops retrying it, and 5xx only for a transient fault
import {
  Body,
  Controller,
  Headers,
  HttpCode,
  Post,
  Req,
  Res,
  UnauthorizedException,
  UsePipes,
  ValidationPipe,
} from '@nestjs/common';
import type { Request, Response } from 'express';
import { WalletCallbackDto } from './wallet.dto';
import { WalletCallbackService } from './wallet-callback.service';

@Controller('teen-patti/wallet')
@UsePipes(new ValidationPipe({ transform: true, whitelist: true }))
export class WalletCallbackController {
  constructor(private readonly wallet: WalletCallbackService) {}

  @Post()
  @HttpCode(200)
  async handle(
    @Req() req: Request,
    @Headers() headers: Record<string, string>,
    @Body() dto: WalletCallbackDto,
    @Res() res: Response,
  ) {
    // rawBody must be the exact bytes that were signed. Re-serialising the
    // parsed object changes the key order and the digest no longer matches --
    // which looks like a signature bug and is not one.
    const raw: Buffer =
      (req as any).rawBody ??
      Buffer.from(JSON.stringify(req.body ?? {}));
    try {
      this.wallet.verify(raw, headers);
    } catch (e) {
      throw e instanceof UnauthorizedException
        ? e
        : new UnauthorizedException('bad signature');
    }
    try {
      const out = await this.wallet.handle(dto);
      res.status(200).json({
        balance: out.balance,
        currency: dto.currency ?? 'COIN',
        transaction_id: dto.transactionId,
        replayed: out.replayed,
      });
    } catch (e) {
      // A 5xx tells the server to retry; a 4xx tells it the request is wrong
      // and must not be. Nothing here returns a fake balance: an unconfigured
      // wallet fails loudly rather than answering 0.
      res.status(503).json({ error: 'wallet unavailable' });
      throw e;
    }
  }
}
