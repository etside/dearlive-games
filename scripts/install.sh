// Generated by the Teen Patti Pro installer.
//
// One event in, one immutable state out. Two things matter more than the
// plumbing: a rejected bet arrives as a socket "error", not as a round event,
// so it needs its own case or a full table reads as a silent no-op; and no
// state here decides an outcome. The server dealt the cards and the server
// says who won.
import 'dart:async';
import 'dart:convert';

import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:web_socket_channel/web_socket_channel.dart';

sealed class TeenPattiEvent {}

class RoundSnapshotReceived extends TeenPattiEvent {
  final Map<String, dynamic> data;
  RoundSnapshotReceived(this.data);
}

class RoundEventReceived extends TeenPattiEvent {
  final String kind;
  final Map<String, dynamic> data;
  RoundEventReceived(this.kind, this.data);
}

class RoundSocketFailed extends TeenPattiEvent {
  final String code;
  RoundSocketFailed(this.code);
}

class RoundConnectionLost extends TeenPattiEvent {
  RoundConnectionLost();
}

enum RoundPhase { idle, connecting, betting, revealed, settled, failed }

class TeenPattiState {
  final RoundPhase phase;
  final Map<String, dynamic>? snapshot;
  final String? lastEventKind;
  final List<String> winners;
  final String? errorCode;

  const TeenPattiState({
    this.phase = RoundPhase.idle,
    this.snapshot,
    this.lastEventKind,
    this.winners = const [],
    this.errorCode,
  });

  int get balance => (snapshot?['balance'] as num?)?.round() ?? 0;
  String get status => (snapshot?['status'] as String?) ?? 'WAITING';
  bool get canBet => phase == RoundPhase.betting && status == 'BETTING_OPEN';

  TeenPattiState copyWith({
    RoundPhase? phase,
    Map<String, dynamic>? snapshot,
    String? lastEventKind,
    List<String>? winners,
    String? errorCode,
  }) =>
      TeenPattiState(
        phase: phase ?? this.phase,
        snapshot: snapshot ?? this.snapshot,
        lastEventKind: lastEventKind ?? this.lastEventKind,
        winners: winners ?? this.winners,
        errorCode: errorCode,
      );
}

class TeenPattiRoundBloc extends Bloc<TeenPattiEvent, TeenPattiState> {
  TeenPattiRoundBloc(WebSocketChannel channel, {required String session})
      : super(const TeenPattiState()) {
    on<RoundSnapshotReceived>((e, emit) {
      final s = e.data['status'] as String? ?? 'WAITING';
      emit(state.copyWith(
        snapshot: e.data,
        phase: _phaseFor(s, state.snapshot),
        errorCode: null,
      ));
    });
    on<RoundEventReceived>((e, emit) {
      // result.declared is when faces may be shown. Before it, the snapshot
      // carries '**' and drawing them would reveal a hand the server has not
      // published.
      if (e.kind == 'result.declared' || e.kind == 'settlement.completed') {
        final w = (e.data['winners'] as List?)?.cast<String>() ?? const [];
        emit(state.copyWith(phase: RoundPhase.settled, winners: w,
                            lastEventKind: e.kind));
      } else {
        emit(state.copyWith(lastEventKind: e.kind));
      }
    });
    on<RoundSocketFailed>((e, emit) =>
        emit(state.copyWith(phase: RoundPhase.failed, errorCode: e.code)));
    on<RoundConnectionLost>((e, emit) =>
        emit(state.copyWith(phase: RoundPhase.connecting)));

    channel.stream.listen(
      (raw) {
        final msg = jsonDecode(raw as String) as Map<String, dynamic>;
        final kind = msg['kind'];
        if (kind == 'snapshot') {
          add(RoundSnapshotReceived(
              (msg['data'] as Map).cast<String, dynamic>()));
        } else if (kind == 'event') {
          final d = (msg['data'] as Map).cast<String, dynamic>();
          add(RoundEventReceived((d['kind'] ?? '') as String, d));
        } else if (kind == 'error') {
          final d = (msg['data'] as Map).cast<String, dynamic>();
          add(RoundSocketFailed((d['code'] ?? 'UNKNOWN') as String));
        }
      },
      onDone: () => add(RoundConnectionLost()),
    );

    channel.sink.add(jsonEncode({'action': 'subscribe', 'session': session}));
  }

  static RoundPhase _phaseFor(String status, Map<String, dynamic>? prev) {
    if (status == 'BETTING_OPEN') return RoundPhase.betting;
    if (status == 'BETTING_CLOSED') return RoundPhase.revealed;
    if (status == 'RESULT' || status == 'SETTLED' || status == 'CLOSED') {
      return RoundPhase.settled;
    }
    return prev == null ? RoundPhase.connecting : RoundPhase.idle;
  }
}
